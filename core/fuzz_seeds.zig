//! stack years ahead of TASK-023/TASK-053 (m-8), this file adds a minimal,
//! private, non-ABI two-player step primitive scoped only to prove
//! permutation invariance — see backlog/decisions/decision-020 for the exact
//! scope and why cross-player body collision is deliberately not modeled.
//!
//! The 256 seeds below are generated by a splitmix64 expansion of a single
//! fixed master constant (a one-time, deterministic codegen step, not a
//! runtime randomness source — see the task's implementation notes for the
//! generating script), the same "generated and independently re-derived,
//! not hand-computed" spirit as docs/rng.md's own test vectors.

