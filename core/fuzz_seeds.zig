// --- invariant 6: permuted multiplayer input-application order ------------
// A minimal, private, non-ABI two-player step primitive — NOT core/world.zig
// and NOT ns_step (that name is reserved for TASK-023/TASK-053's real C-ABI
// lockstep primitive). See backlog/decisions/decision-020 for exact scope:
// two players share board dimensions, one global food cell, and one RNG
// stream, resolved in ascending player index order (docs/abi-decisions.md
// freeze #1, docs/rng.md "Food placement" point 3); cross-player body
// collision is deliberately not modeled.

const MULTI_PLAYERS = 2;

const MultiPlayer = struct {
    status: canon.Status,
    dir: canon.Dir,
    next_dir: canon.Dir,
    score: u32,
    cells_buf: []canon.Cell,
    cells_len: u32,
};

fn multiOccupied(players: *const [MULTI_PLAYERS]MultiPlayer, x: u16, y: u16) bool {
    for (players) |p| {
        if (p.status == .dead) continue;
        for (p.cells_buf[0..p.cells_len]) |c| {
            if (c.x == x and c.y == y) return true;
        }
    }
    return false;
}

/// Row-major free-cell draw across every live player's body (docs/rng.md
/// "Food placement" #1-2, extended to "any player's body" since food is a
/// single global cell here, same as docs/canonical-state.md).
fn placeFoodShared(cols: u16, rows: u16, players: *const [MULTI_PLAYERS]MultiPlayer, food: *?canon.Cell, r: *rng.Rng) void {
    var occupied_count: u32 = 0;
    for (players) |p| {
        if (p.status != .dead) occupied_count += p.cells_len;
    }
    const total = @as(u32, cols) * @as(u32, rows);
    const free = total - occupied_count;
    if (free == 0) {
        food.* = null;
        return;
    }
    const idx = r.boundedDraw(free);
    var seen: u32 = 0;
    for (0..rows) |y| {
        for (0..cols) |x| {
            if (multiOccupied(players, @intCast(x), @intCast(y))) continue;
            if (seen == idx) {
                food.* = .{ .x = @intCast(x), .y = @intCast(y) };
                return;
            }
            seen += 1;
        }
    }
    unreachable;
}

/// One shared tick, in two phases so that `order` (the permutation under
/// test) can only ever affect phase 1: dir commit + move + wall/self
/// collision, computed per player against the tick's *starting* food value,
/// mutating nothing shared. Phase 2 — body mutation, food consumption, and
/// the one shared-RNG food replacement draw — always runs in fixed
/// ascending player index order, never `order`, which is what makes the
/// permutation provably unable to change the result.
fn stepTick(
    cols: u16,
    rows: u16,
    players: *[MULTI_PLAYERS]MultiPlayer,
    dirs: [MULTI_PLAYERS]canon.Dir,
    food: *?canon.Cell,
    r: *rng.Rng,
    order: [MULTI_PLAYERS]usize,
) void {
    var died: [MULTI_PLAYERS]bool = .{ false, false };
    var new_head: [MULTI_PLAYERS]canon.Cell = undefined;
    var would_eat: [MULTI_PLAYERS]bool = .{ false, false };

    // Phase 1 (order under test): read-only against `food.*`, no shared mutation.
    for (order) |i| {
        var p = &players[i];
        if (p.status == .dead) {
            died[i] = true;
            continue;
        }
        p.dir = dirs[i];
        p.next_dir = dirs[i];

        const head = p.cells_buf[0];
        const v = world.DIR_VEC[@intFromEnum(p.dir)];
        const nx: i32 = @as(i32, head.x) + @as(i32, v.dx);
        const ny: i32 = @as(i32, head.y) + @as(i32, v.dy);
        if (nx < 0 or ny < 0 or nx >= @as(i32, cols) or ny >= @as(i32, rows)) {
            died[i] = true;
            continue;
        }
        const nc = canon.Cell{ .x = @intCast(nx), .y = @intCast(ny) };
        const eating = food.* != null and nc.x == food.*.?.x and nc.y == food.*.?.y;
        const check_len: u32 = if (eating) p.cells_len else p.cells_len - 1;
        var self_hit = false;
        for (0..check_len) |k| {
            if (p.cells_buf[k].x == nc.x and p.cells_buf[k].y == nc.y) {
                self_hit = true;
                break;
            }
        }
        if (self_hit) {
            died[i] = true;
            continue;
        }
        new_head[i] = nc;
        would_eat[i] = eating;
    }

    // Phase 2 (fixed ascending index, never `order`): mutate bodies, resolve
    // shared food, draw the one shared-RNG replacement if anything was eaten.
    var need_new_food = false;
    for (0..MULTI_PLAYERS) |i| {
        var p = &players[i];
        if (died[i]) {
            p.status = .dead;
            continue;
        }
        const confirmed_eat = would_eat[i] and food.* != null;
        const buf = p.cells_buf[0 .. p.cells_len + 1];
        std.mem.copyBackwards(canon.Cell, buf[1..], buf[0..p.cells_len]);
        p.cells_buf[0] = new_head[i];
        if (confirmed_eat) {
            p.cells_len += 1;
            p.score += 10;
            food.* = null;
            need_new_food = true;
        }
    }
    if (need_new_food) placeFoodShared(cols, rows, players, food, r);
}

const MultiResult = struct {
    tick: u32,
    food: ?canon.Cell,
    rng_state: [4]u32,
    players: [MULTI_PLAYERS]MultiPlayer,
};

/// Runs TICKS ticks of the two-player primitive from `seed`, applying
/// per-tick input in `order`. Both players' turn sequences come from the
/// same deterministic per-tick generator regardless of `order` — only the
/// *order in which stepTick visits players within phase 1* varies, which is
/// exactly the "permuted input-application order" AC#2 asks to be explicit
/// about (network input for different players arriving interleaved, not the
/// players choosing different moves).
fn driveMulti(seed: [4]u32, order: [MULTI_PLAYERS]usize, bufs: [MULTI_PLAYERS][]canon.Cell) MultiResult {
    var players: [MULTI_PLAYERS]MultiPlayer = undefined;
    for (0..MULTI_PLAYERS) |i| {
        const cy = ROWS / 2 + @as(u16, @intCast(i)) * 2; // distinct starting rows, off each other's path
        bufs[i][0] = .{ .x = 8, .y = cy };
        bufs[i][1] = .{ .x = 7, .y = cy };
        bufs[i][2] = .{ .x = 6, .y = cy };
        players[i] = .{
            .status = .playing,
            .dir = .right,
            .next_dir = .right,
            .score = 0,
            .cells_buf = bufs[i],
            .cells_len = 3,
        };
    }

    var r = rng.Rng.init(seed);
    var food: ?canon.Cell = null;
    placeFoodShared(COLS, ROWS, &players, &food, &r);

    var turn_streams: [MULTI_PLAYERS]rng.Rng = undefined;
    for (0..MULTI_PLAYERS) |i| {
        turn_streams[i] = auxRng(seed, .{
            0x9E3779B1 *% @as(u32, @intCast(i + 1)),
            0x85EBCA77 *% @as(u32, @intCast(i + 1)),
            0xC2B2AE3D *% @as(u32, @intCast(i + 1)),
            0x27D4EB2F *% @as(u32, @intCast(i + 1)),
        });
    }

    var tick: u32 = 0;
    while (tick < TICKS) : (tick += 1) {
        var any_alive = false;
        for (players) |p| {
            if (p.status != .dead) any_alive = true;
        }
        if (!any_alive) break;

        var dirs: [MULTI_PLAYERS]canon.Dir = undefined;
        for (0..MULTI_PLAYERS) |i| {
            dirs[i] = turnedDir(players[i].dir, nextTurn(&turn_streams[i]));
        }
        stepTick(COLS, ROWS, &players, dirs, &food, &r, order);
    }

    return .{ .tick = tick, .food = food, .rng_state = r.state(), .players = players };
}

fn multiChecksum(result: MultiResult) u64 {
    var players_arr: [MULTI_PLAYERS]canon.Player = undefined;
    for (0..MULTI_PLAYERS) |i| {
        players_arr[i] = .{
            .status = result.players[i].status,
            .dir = result.players[i].dir,
            .next_dir = result.players[i].next_dir,
            .score = result.players[i].score,
            .cells = result.players[i].cells_buf[0..result.players[i].cells_len],
        };
    }
    const state = canon.State{
        .cols = COLS,
        .rows = ROWS,
        .wrap = false,
        .tick = result.tick,
        .rng_state = result.rng_state,
        .food = result.food,
        .players = &players_arr,
    };
    var enc: [canon.HEADER_BYTES + MULTI_PLAYERS * canon.PLAYER_FIXED_BYTES + 4 * COLS * ROWS + canon.CHECKSUM_BYTES]u8 = undefined;
    const rec = canon.encode(state, &enc) catch unreachable;
    return canon.checksum(rec);
}

test "permuted per-tick input-application order yields identical checksums for all 256 seeds" {
    var bufs_a: [MULTI_PLAYERS][COLS * ROWS]canon.Cell = undefined;
    var bufs_b: [MULTI_PLAYERS][COLS * ROWS]canon.Cell = undefined;
    var slices_a: [MULTI_PLAYERS][]canon.Cell = undefined;
    var slices_b: [MULTI_PLAYERS][]canon.Cell = undefined;
    for (0..MULTI_PLAYERS) |i| {
        slices_a[i] = &bufs_a[i];
        slices_b[i] = &bufs_b[i];
    }

    for (SEEDS) |seed| {
        const ascending = driveMulti(seed, .{ 0, 1 }, slices_a);
        const reversed = driveMulti(seed, .{ 1, 0 }, slices_b);
        try std.testing.expectEqual(multiChecksum(ascending), multiChecksum(reversed));
    }
}
