//! Tier-B fuzz invariants (TASK-021): 256 committed seeds checked against
//! structural invariants, not the oracle checksum (docs/build-layout.md's
//! Tier-A/Tier-B split — Tier-A is single-behavior unit tests, Tier-B is
//! broad seed coverage). Unlike core/difftest.zig (TASK-020), there is no
//! oracle-recorded expectation to replay here: these are properties that
//! must hold for *any* legal sequence of inputs, so each is checked directly
//! against core/world.zig's own output rather than a recorded trace.
//!
//! Invariants 1-5 drive a single-player core/world.zig.World directly.
//! Invariant 6 needs more than one player moving in the same tick, which
//! core/world.zig does not model (it is deliberately single-player — see its
