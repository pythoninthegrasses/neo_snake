/// Turn relative to the current direction: never a reversal, so this never
/// trips queueDir's 180 guard and never needs to filter anything out —
/// every draw is legal input by construction.
const Turn = enum(u2) { straight, left, right };

const LEFT_OF = [4]canon.Dir{ .left, .right, .down, .up }; // indexed by current dir
const RIGHT_OF = [4]canon.Dir{ .right, .left, .up, .down };

fn turnedDir(cur: canon.Dir, t: Turn) canon.Dir {
    return switch (t) {
        .straight => cur,
        .left => LEFT_OF[@intFromEnum(cur)],
        .right => RIGHT_OF[@intFromEnum(cur)],
    };
}

/// Deterministic per-tick turn generator: an auxiliary xoshiro128** stream,
/// seeded from the seed under test XORed with a caller-supplied salt so
/// distinct players/purposes never draw from the same stream as the
/// simulation's own shared RNG. This is a test-input generator, not part of
/// the simulation.
fn auxRng(seed: [4]u32, salt: [4]u32) rng.Rng {
    var s = seed;
    for (0..4) |i| s[i] ^= salt[i];
    if (s[0] == 0 and s[1] == 0 and s[2] == 0 and s[3] == 0) s[0] = 1;
    return rng.Rng.init(s);
}

fn nextTurn(r: *rng.Rng) Turn {
    return @enumFromInt(@as(u2, @intCast(r.boundedDraw(3))));
}

// --- invariants 1-5: single-player, driving core/world.zig directly -------

fn driveSingle(seed: [4]u32, buf: []canon.Cell) world.World {
    var w: world.World = undefined;
    world.initWorld(&w, buf, COLS, ROWS, false, seed, .playing);

    var turns = auxRng(seed, .{ 0x9E3779B1, 0x85EBCA77, 0xC2B2AE3D, 0x27D4EB2F });
    var tick: u32 = 0;
    while (tick < TICKS and w.status == .playing) : (tick += 1) {
        world.queueDir(&w, turnedDir(w.dir, nextTurn(&turns)));
        world.advance(&w);
        checkStructuralInvariants(&w);
    }
    return w;
}

/// Invariants 1-3, checked after every tick (not just the final one) so a
/// regression is caught at the first tick it appears, not masked by a later
/// tick coincidentally restoring the property.
fn checkStructuralInvariants(w: *world.World) void {
    // #1: body_len == 3 + score/10 (grows by exactly one cell per 10-point eat).
    std.debug.assert(w.cells_len == 3 + w.score / 10);

    const live = world.cells(w);

    // #2: no duplicate body cells.
    for (0..live.len) |i| {
        for (i + 1..live.len) |j| {
            std.debug.assert(!(live[i].x == live[j].x and live[i].y == live[j].y));
        }
    }

    // #3: food never placed on a body cell.
    if (w.food) |f| {
        for (live) |c| {
            std.debug.assert(!(c.x == f.x and c.y == f.y));
        }
    }
}

/// `players_buf` must outlive the returned State — it borrows `players_buf[0..1]`
/// rather than allocating (this module has no allocator), so the caller owns
/// the storage, not a function-local temporary that would dangle on return.
fn stateOf(w: *const world.World, players_buf: *[1]canon.Player) canon.State {
    players_buf[0] = .{
        .status = w.status,
        .dir = w.dir,
        .next_dir = w.next_dir,
        .score = w.score,
        .cells = world.cells(w),
    };
    return .{
        .cols = w.cols,
        .rows = w.rows,
        .wrap = w.wrap,
        .tick = w.tick,
        .rng_state = w.rng.state(),
        .food = w.food,
        .players = players_buf,
    };
}

